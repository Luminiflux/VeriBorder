function load(code) {
  return JSON.parse(fs.readFileSync(path.join(LANG_DIR, `${code}.json`), 'utf8'));
}

function write(code, data) {
  const sorted = {};
  for (const key of Object.keys(data).sort()) sorted[key] = data[key];
  fs.writeFileSync(path.join(LANG_DIR, `${code}.json`),
    JSON.stringify(sorted, null, 2) + '\n', 'utf8');
  console.log(`${code}: ${Object.keys(sorted).length} keys`);
}

